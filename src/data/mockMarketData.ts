export function generateCandleHistory(basePrice: number, points = 45): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let currentClose = basePrice * 0.94;
  const now = new Date();

  for (let i = points; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 3600 * 1000 * 4);
    const timeStr = `${d.getMonth() + 1}/${d.getDate()} ${String(d.getHours()).padStart(2, '0')}:00`;
    const volatility = basePrice * 0.012;
    const change = (Math.random() - 0.48) * volatility;
    const open = currentClose;
    const close = Math.max(open + change, basePrice * 0.5);
    const high = Math.max(open, close) + Math.random() * (volatility * 0.7);
    const low = Math.min(open, close) - Math.random() * (volatility * 0.7);
    const volume = Math.floor(Math.random() * 500000 + 100000);

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentClose = close;
  }

  // Ensure last candle matches basePrice closely
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}
